export function getPastExamByNumber(num) {
  return ONET_PAST_EXAM_BANK.find(q => q.number === Number(num)) || null;
}

export function getPastExamsByIndicator(indicator) {
  return ONET_PAST_EXAM_BANK.filter(q => q.indicator.includes(indicator));
}

