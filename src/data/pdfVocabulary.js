const SET_SIZE = 25;
export const PDF_VOCABULARY_SUMMARY = Object.freeze({
  uniqueWords: PDF_VOCABULARY_ENTRIES.length,
  sourceOccurrences: PDF_VOCABULARY_ENTRIES.reduce((n,e)=>n+e.sourceRefs.length,0),
  sets: Math.ceil(PDF_VOCABULARY_ENTRIES.length / SET_SIZE),
});
export const PDF_VOCABULARY_CATEGORIES = Array.from({length:PDF_VOCABULARY_SUMMARY.sets},(_,index)=>{
  const words=PDF_VOCABULARY_ENTRIES.slice(index*SET_SIZE,(index+1)*SET_SIZE);
  const id=`pdf_vocab_set_${String(index+1).padStart(2,'0')}`;
  return {id,deckId:id,group:'pdf_vocabulary',presentation:'text',tone:['sky','mint','lilac','peach'][index%4],
    name:`ชุด ${String(index+1).padStart(2,'0')} · ${words[0].word} – ${words.at(-1).word}`,
    sourceNote:'คำศัพท์จากฉบับนักเรียน หน้า 3–10 · เรียนครั้งละไม่เกิน 25 คำ/วลี'};
});

export function getPdfVocabularyMission(deckId) {
  const index=PDF_VOCABULARY_CATEGORIES.findIndex(c=>c.deckId===deckId);
  if(index<0) return null;
  return {id:deckId,title:PDF_VOCABULARY_CATEGORIES[index].name,type:'flashcard',xpReward:30,
    assessmentEligible:false,contentStatus:'source_transcription_learning_only',
    source:{id:'student-challenge-2569',pdfPages:[3,4,5,6,7,8,9,10]},
    cards:PDF_VOCABULARY_ENTRIES.slice(index*SET_SIZE,(index+1)*SET_SIZE).map(entry=>({
      id:entry.id,front:entry.word,frontLabel:entry.word,frontType:'text',back:entry.word,
      backThai:entry.meaningTh,learningOnly:true,hint:entry.teachingNote || undefined,
      sourceMeanings:[...entry.sourceMeanings],sourceRefs:entry.sourceRefs.map(ref=>({...ref})),
    })),
  };
}
